#!/usr/bin/env python3
"""Download public FX research data (FRED, ECB, CFTC COT) into data/raw with provenance.
Re-runnable: a file whose sha256 matches provenance.json is not downloaded again.
Usage: python3 fetch_fx.py   (logs to data/fetch.log and stderr)
"""
import hashlib, json, logging, os, stat, sys, time, urllib.request, urllib.error
from datetime import datetime, timezone

BASE = os.path.expanduser("~/claude_master/w3/fx/data")
RAW = os.path.join(BASE, "raw")
PROV_JSON = os.path.join(BASE, "provenance.json")
PROV_MD = os.path.join(BASE, "PROVENANCE.md")
UA = "Mozilla/5.0 (X11; Linux x86_64) research-data-fetch/1.0"
MAX_FILE = 200 * 1024 * 1024
MAX_TOTAL = 500 * 1024 * 1024
PAUSE = 1.5

FRED_IDS = ["DEXUSEU", "DEXJPUS", "DEXUSUK", "DEXSZUS", "DEXCAUS", "DEXUSAL", "DEXUSNZ", "DEXNOUS", "DEXSDUS", "VIXCLS",
            "IR3TIB01USM156N", "IR3TIB01EZM156N", "IR3TIB01GBM156N", "IR3TIB01JPM156N", "IR3TIB01CHM156N",
            "IR3TIB01CAM156N", "IR3TIB01AUM156N", "IR3TIB01NZM156N", "IR3TIB01NOM156N", "IR3TIB01SEM156N"]
CFTC = "https://www.cftc.gov/files/dea/history/"


def targets():
    t = [("FRED_%s.csv" % i, "https://fred.stlouisfed.org/graph/fredgraph.csv?id=%s" % i) for i in FRED_IDS]
    t.append(("eurofxref-hist.zip", "https://www.ecb.europa.eu/stats/eurofxref/eurofxref-hist.zip"))
    t.append(("deacot1986_2016.zip", CFTC + "deacot1986_2016.zip"))
    t += [("deacot%d.zip" % y, CFTC + "deacot%d.zip" % y) for y in range(2017, 2027)]
    t.append(("fin_fut_txt_2006_2016.zip", CFTC + "fin_fut_txt_2006_2016.zip"))
    t += [("fut_fin_txt_%d.zip" % y, CFTC + "fut_fin_txt_%d.zip" % y) for y in range(2017, 2027)]
    return t


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def load_prov():
    if os.path.exists(PROV_JSON):
        with open(PROV_JSON) as f:
            return json.load(f)
    return {}


def save_prov(prov):
    tmp = PROV_JSON + ".tmp"
    with open(tmp, "w") as f:
        json.dump(prov, f, indent=1, sort_keys=True)
    os.replace(tmp, PROV_JSON)
    lines = ["# PROVENANCE - FX raw data", "",
             "Generated by code/fetch_fx.py. Raw files are read-only (chmod a-w). Times are UTC.", "",
             "| file | url | downloaded_utc | bytes | sha256 | http |", "|---|---|---|---|---|---|"]
    for k in sorted(prov):
        p = prov[k]
        lines.append("| %s | %s | %s | %s | %s | %s |" % (k, p.get("url"), p.get("downloaded_utc"), p.get("bytes"),
                                                       p.get("sha256"), p.get("http")))
    with open(PROV_MD, "w") as f:
        f.write("\n".join(lines) + "\n")


def fetch(name, url, prov, total):
    path = os.path.join(RAW, name)
    if os.path.exists(path) and name in prov and prov[name].get("sha256") == sha256(path):
        logging.info("skip %s (sha matches provenance)", name)
        return total, False
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
    when = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    try:
        with urllib.request.urlopen(req, timeout=180) as r:
            code = r.status
            clen = r.headers.get("Content-Length")
            if clen and int(clen) > MAX_FILE:
                raise SystemExit("ABORT: %s Content-Length %s > 200MB" % (name, clen))
            data = bytearray()
            while True:
                b = r.read(1 << 20)
                if not b:
                    break
                data += b
                if len(data) > MAX_FILE:
                    raise SystemExit("ABORT: %s exceeds 200MB" % name)
    except urllib.error.HTTPError as e:
        body = e.read(300).decode("latin-1", "replace").replace("\n", " ")
        logging.error("FAIL %s HTTP %s %s body=%r", name, e.code, e.reason, body)
        prov[name + ".FAILED"] = {"url": url, "downloaded_utc": when, "http": e.code, "error": "%s %s" % (e.code, e.reason)}
        return total, True
    except urllib.error.URLError as e:
        logging.error("FAIL %s URLError %s", name, e.reason)
        prov[name + ".FAILED"] = {"url": url, "downloaded_utc": when, "http": None, "error": str(e.reason)}
        return total, True
    if total + len(data) > MAX_TOTAL:
        raise SystemExit("ABORT: total download would exceed 500MB at %s" % name)
    tmp = path + ".part"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)
    os.chmod(path, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
    prov.pop(name + ".FAILED", None)
    prov[name] = {"url": url, "downloaded_utc": when, "bytes": len(data), "sha256": sha256(path), "http": code}
    logging.info("ok %s http=%s bytes=%d", name, code, len(data))
    return total + len(data), True


def main():
    os.makedirs(RAW, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s",
                        handlers=[logging.FileHandler(os.path.join(BASE, "fetch.log")), logging.StreamHandler(sys.stderr)])
    prov = load_prov()
    total = 0
    only = set(sys.argv[1:])
    for name, url in targets():
        if only and name not in only:
            continue
        total, hit = fetch(name, url, prov, total)
        save_prov(prov)
        if hit:
            time.sleep(PAUSE)
    logging.info("done, downloaded this run: %d bytes", total)


if __name__ == "__main__":
    main()
